const path = require('node:path')
const { spawn } = require('node:child_process')
const root = path.resolve(__dirname, '..')
const express = require(path.join(root, 'backend/node_modules/express'))
const app = express()
app.use('/imagens', express.static(path.join(root, 'imagens')))
app.use('/videos', express.static(path.join(root, 'videos')))
app.use(express.static(path.join(root, 'frontend')))
const front = app.listen(Number(process.env.FRONTEND_PORT) || 5500, '127.0.0.1', () => console.log('Frontend: http://localhost:' + (process.env.FRONTEND_PORT || 5500)))
const api = spawn(process.execPath, ['server.js'], { cwd: path.join(root, 'backend'), stdio: 'inherit', windowsHide: true })
const parar = () => { api.kill(); front.close() }
front.on('error', err => { console.error('Não foi possível abrir o frontend:', err.code); api.kill(); process.exitCode = 1 })
api.on('exit', codigo => { front.close(); if (codigo) process.exitCode = codigo })
process.once('SIGINT', parar); process.once('SIGTERM', parar)
