const { test, before, after } = require('node:test')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const os = require('node:os')
const { chromium } = require('playwright')
let a, browser, front, base
before(async () => {
    a = await require('./helpers/app').ambiente()
    const express = require('express'), app = express(), root = path.join(__dirname, '../..')
    app.use('/imagens', express.static(path.join(root, 'imagens')))
    app.use('/videos', express.static(path.join(root, 'videos')))
    app.use(express.static(path.join(root, 'frontend')))
    front = await new Promise(resolve => { const s = app.listen(0,'127.0.0.1',()=>resolve(s)) })
    base = `http://127.0.0.1:${front.address().port}/`
    const chrome = 'C:/Program Files/Google/Chrome/Application/chrome.exe'
    browser = await chromium.launch({ headless: true, ...(fs.existsSync(chrome) ? { executablePath: chrome } : {}) })
})
after(async () => {
    if (browser) await browser.close()
    if (front) await new Promise(resolve => front.close(resolve))
    if (a) await a.fechar()
})
async function contexto(viewport, admin = false) {
    const context = await browser.newContext({ viewport })
    await context.route('https://fonts.googleapis.com/**', route => route.abort())
    await context.route('https://www.youtube-nocookie.com/**', route => route.abort())
    await context.route('**/videos/**', route => route.abort())
    await context.route('http://localhost:3001/api/**', async route => {
        const response = await route.fetch({ url: route.request().url().replace('http://localhost:3001/api', a.base) })
        await route.fulfill({ response })
    })
    if (admin) await context.addInitScript(({ token, id }) => {
        localStorage.setItem('sk_token', token); localStorage.setItem('sk_user', JSON.stringify({ id, nome: 'Gestor Teste', tipo: 'ADMIN' }))
    }, { token: a.tokens.gestor, id: a.gestor.codUsuario })
    const page = await context.newPage(); page.setDefaultTimeout(10000)
    const erros = []; page.on('pageerror', e => erros.push(e.message)); page.on('dialog', dialog => dialog.accept())
    return { context, page, erros }
}
